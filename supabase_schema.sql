-- ---------- updated_at helper ----------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array['profiles','organisasi','surat_masuk','disposisi','surat_keluar','nomor_surat'] loop
    execute format('drop trigger if exists touch_updated_at on public.%I',t);
    execute format('create trigger touch_updated_at before update on public.%I for each row execute function public.touch_updated_at()',t);
  end loop;
end $$;

-- ---------- nomor otomatis ----------
create or replace function public.ambil_nomor_surat(p_tahun integer, p_bulan integer)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_last integer;
  v_next integer;
  v_fmt text;
  v_kode_org text;
  v_kode_sek text;
  v_romawi text;
  v_result text;
begin
  insert into public.nomor_surat(tahun, nomor_terakhir)
  values (p_tahun,0)
  on conflict (tahun) do nothing;

  select nomor_terakhir, format_nomor, kode_organisasi, kode_sekretariat
    into v_last, v_fmt, v_kode_org, v_kode_sek
  from public.nomor_surat where tahun=p_tahun for update;

  v_next := v_last + 1;
  update public.nomor_surat set nomor_terakhir=v_next where tahun=p_tahun;

  v_romawi := case p_bulan
    when 1 then 'I' when 2 then 'II' when 3 then 'III' when 4 then 'IV'
    when 5 then 'V' when 6 then 'VI' when 7 then 'VII' when 8 then 'VIII'
    when 9 then 'IX' when 10 then 'X' when 11 then 'XI' when 12 then 'XII'
    else to_char(p_bulan,'FM00') end;

  v_result := replace(v_fmt,'{nomor}',lpad(v_next::text,3,'0'));
  v_result := replace(v_result,'{bulan}',lpad(p_bulan::text,2,'0'));
  v_result := replace(v_result,'{bulan_romawi}',v_romawi);
  v_result := replace(v_result,'{tahun}',p_tahun::text);
  v_result := replace(v_result,'{kode_organisasi}',coalesce(v_kode_org,'ORG'));
  v_result := replace(v_result,'{kode_sekretariat}',coalesce(v_kode_sek,'SEK'));
  return v_result;
end;
$$;
grant execute on function public.ambil_nomor_surat(integer,integer) to authenticated;

