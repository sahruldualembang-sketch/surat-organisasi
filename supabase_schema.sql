create extension if not exists pgcrypto;

-- ---------- profiles ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nama text not null default '',
  username text unique,
  email text,
  jabatan text,
  role text not null default 'Pengurus' check (role in ('Admin','Sekretaris','Pengurus')),
  status text not null default 'Aktif' check (status in ('Aktif','Nonaktif')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- helper roles ----------
-- Dibuat setelah tabel profiles karena fungsi-fungsi ini membacanya.
create or replace function public.current_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select role from public.profiles where id = auth.uid()), 'Pengurus');
$$;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_role() in ('Admin','Sekretaris');
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_role() = 'Admin';
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id,nama,username,email,jabatan,role,status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nama', split_part(coalesce(new.email,''),'@',1)),
    nullif(new.raw_user_meta_data->>'username',''),
    new.email,
    nullif(new.raw_user_meta_data->>'jabatan',''),
    'Pengurus',
    'Aktif'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

